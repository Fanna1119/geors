#!/usr/bin/env python3
"""Sample real places from a geors data directory for the demo page.

Usage: examples/demo/make-data.py [DATA_DIR] [GEORS_BINARY]

Writes examples/demo/demo-data.js: per continent, coordinates for reverse
geocoding and search queries (names with their city, and full addresses),
taken from `geors export` of the partitions listed below. Countries that are
not in the data directory are skipped.
"""
import json
import os
import random
import subprocess
import sys

DATA = sys.argv[1] if len(sys.argv) > 1 else "data"
GEORS = sys.argv[2] if len(sys.argv) > 2 else "target/release/geors"
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "demo-data.js")
PER_COUNTRY = 1500  # places sampled per country

CONTINENTS = {
    "na": {
        "name": "North America",
        "countries": ["us", "ca", "mx"],
        "bounds": [[-125.0, 15.0], [-60.0, 55.0]],
    },
    "eu": {
        "name": "Europe",
        "countries": ["de", "fr", "gb", "it", "es", "nl", "pl", "se", "at", "ch"],
        "bounds": [[-10.0, 36.0], [25.0, 60.0]],
    },
    "as": {
        "name": "Asia",
        "countries": ["jp", "in", "cn", "kr", "th", "id", "tw", "vn", "ph", "my"],
        "bounds": [[68.0, -8.0], [146.0, 46.0]],
    },
}


def places_in(cc):
    meta = os.path.join(DATA, cc, "meta.json")
    if not os.path.exists(meta):
        return 0
    with open(meta) as f:
        return json.load(f)["num_places"]


def export(cc):
    every = max(1, places_in(cc) // PER_COUNTRY)
    out = subprocess.run(
        [GEORS, "export", "--data", DATA, "--every", str(every), cc],
        check=True, capture_output=True, text=True,
    ).stdout
    return [json.loads(line) for line in out.splitlines() if line]


def city_of(p):
    if p.get("city"):
        return p["city"]
    for parent in p.get("parents", []):
        layer, _, name = parent.partition(":")
        if layer in ("city", "district", "locality"):
            return name
    return None


def query_of(p):
    """A search for the place: full address for houses, name + city else."""
    city = city_of(p)
    if p["layer"] == "house" and p.get("street") and p.get("housenumber") and city:
        return f"{p['street']} {p['housenumber']}, {city}"
    if p.get("name") and p["layer"] in ("poi", "street", "city", "locality"):
        return f"{p['name']}, {city}" if city and city != p["name"] else p["name"]
    return None


random.seed(42)
result = {}
for key, c in CONTINENTS.items():
    points, searches = [], []
    for cc in c["countries"]:
        if not places_in(cc):
            print(f"  {cc}: not in {DATA}, skipped", file=sys.stderr)
            continue
        rows = export(cc)
        print(f"  {cc}: {len(rows)} places", file=sys.stderr)
        for p in rows:
            lon, lat = p["center"]["lon"], p["center"]["lat"]
            points.append([round(lon, 6), round(lat, 6)])
            q = query_of(p)
            if q:
                searches.append({"q": q, "lon": round(lon, 6), "lat": round(lat, 6), "cc": cc})
    random.shuffle(points)
    random.shuffle(searches)
    # Full addresses make the best world-tour stops.
    tour = [s for s in searches if any(ch.isdigit() for ch in s["q"])][:4] or searches[:4]
    result[key] = {
        "name": c["name"],
        "bounds": c["bounds"],
        "points": points[:6000],
        "searches": searches[:3000],
        "tour": tour,
    }
    print(f"{c['name']}: {len(points)} points, {len(searches)} searches", file=sys.stderr)

with open(OUT, "w") as f:
    f.write("// Generated by make-data.py from " + DATA + "; not committed.\n")
    f.write("window.DEMO_DATA = ")
    json.dump(result, f, ensure_ascii=False, separators=(",", ":"))
    f.write(";\n")
print(f"wrote {OUT}", file=sys.stderr)
